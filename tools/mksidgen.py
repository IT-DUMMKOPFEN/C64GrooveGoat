#!/usr/bin/env python3
# C64 GrooveGoat - export the SIDGen data (styles, instruments, filter programs)
# into src/gsgdata.c for the C port of the SIDGen composer and MIDI importer.
#
#   python3 tools/mksidgen.py /path/to/sidgen
#
# SIDGen (https://github.com/IT-DUMMKOPFEN/sidgen) is only read, never changed.

import json
import os
import sys

SG = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/sidgen'
sys.path.insert(0, SG)

from sidgen import styles as S          # noqa: E402
from sidgen import instruments as I     # noqa: E402
from sidgen import genlib as GL         # noqa: E402
from sidgen import timbre as T          # noqa: E402
from sidgen.i18n import en              # noqa: E402
from sidgen.version import VERSION      # noqa: E402

try:
    from sidgen.filter8580_data import SCALE8580
except ImportError:
    SCALE8580 = {}
try:
    from sidgen.punch_data import PUNCH
except ImportError:
    PUNCH = {}
try:
    from sidgen.loudness_table import LOUD
except ImportError:
    LOUD = {}

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'gsgdata.c')


def cstr(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif 32 <= o < 127:
            out.append(ch)
        else:
            for b in ch.encode('utf-8'):
                out.append('\\%03o' % b)
    return '"' + ''.join(out) + '"'


def chunks(s, n=2000):
    return [s[i:i + n] for i in range(0, len(s), n)] or ['']


def hexprog(prog):
    out = []
    for l, r in prog or []:
        if isinstance(r, tuple):
            r = 0x100 | (r[1] & 0x0F)
        out.append('%02x%03x' % (l & 0xFF, r))
    return ''.join(out)


lines = []
lines.append('// Generated by tools/mksidgen.py from SIDGen %s - do not edit.' % VERSION)
lines.append('// SIDGen: https://github.com/IT-DUMMKOPFEN/sidgen (IT-DUMMKOPFEN)')
lines.append('#include "gsg.h"')
lines.append('')
lines.append('const char *sg_version = %s;' % cstr(VERSION))

# ------------------------------------------------------------------ styles
variants = []
for k in S.STYLE_ORDER:
    st = S.STYLES[k]
    subs = st.get('subs') or []
    if subs:
        for i, (sub, w) in enumerate(subs):
            variants.append((k, i, w, S.sub_style(k, i)))
    else:
        variants.append((k, -1, 1, st))

lines.append('const int sg_numstyles = %d;' % len(variants))
lines.append('const SGSTYLEREF sg_styles[] = {')
for k, i, w, st in variants:
    d = {f: v for f, v in st.items() if f != 'subs'}
    js = json.dumps(d, separators=(',', ':'), ensure_ascii=True, default=list)
    parts = ' '.join(cstr(c) for c in chunks(js))
    lines.append('  {%s, %s, %s, %d, %s,\n   %s},' % (cstr(k), cstr(st['name']), cstr(st.get('sub_name') or ''),
                                                      w, cstr(st.get('desc', '')), parts))
lines.append('};')

# ------------------------------------------------------------- instruments


def fam(ins):
    try:
        return T.family(ins)
    except Exception:
        return ins.cat


def insline(ins, model):
    vib = '%d,%d' % (ins.vib[0], ins.vib[1]) if ins.vib else ''
    f = ins.filt or ''
    return '\t'.join([ins.name, ins.cat, fam(ins) or '', getattr(ins, 'theme', None) or '', str(model),
                      '%d' % ins.ad, '%d' % ins.sr, '%d' % ins.gt, '%d' % ins.fw, vib, '%d' % (ins.vibdelay or 0),
                      f, hexprog(ins.wave), hexprog(ins.pulse), en(ins.name),
                      '%s' % (round(ins.level, 1) if getattr(ins, 'level', None) is not None else ''),
                      getattr(ins, 'group', None) or ''])


rows = []
for ins in I.LIB:
    rows.append(insline(ins, 0))
for model in (6581, 8580):
    for ins in GL.GEN.get(model, []):
        rows.append(insline(ins, model))
text = '\n'.join(rows) + '\n'
lines.append('const int sg_numinstr = %d;' % len(rows))
lines.append('const char *sg_instrtext[] = {')
for c in chunks(text, 3000):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')

# word list of SIDGen's English names (i18n._translate)
from sidgen import i18n as I18N
lines.append('const char *sg_wordtext[] = {')
for c in chunks('\n'.join('%s\t%s' % kv for kv in I18N.WORDS.items()) + '\n', 3000):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')

# arpeggio templates: name, ad, sr, wavebyte, speed, octave, pulse, filt, english name
arows = []
for t in I.ARPS:
    arows.append('\t'.join([t.name, '%d' % t.ad, '%d' % t.sr, '%d' % t.wavebyte, '%d' % t.speed,
                            '1' if t.octave else '0', hexprog(t.pulse), t.filt or '', en(t.name)]))
# English names of the arpeggio instruments (template x chord type)
aen = []
for t in I.ARPS:
    for q in I.CHORD_TYPES:
        ins = t.make(q)
        aen.append('%s\t%s' % (ins.name, en(ins.name)))
lines.append('const char *sg_arpentext[] = {')
for c in chunks('\n'.join(aen) + '\n', 3000):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')
lines.append('const char *sg_arptext = %s;' % ' '.join(cstr(c) for c in chunks('\n'.join(arows) + '\n')))

# chord types (order of the arpeggio library files: maj min dim aug sus4 sus2 maj7 min7 dom7 pow min6 maj6)
ct = []
for q, iv in I.CHORD_TYPES.items():
    ct.append('%s:%s:%s' % (q, ','.join(str(x) for x in iv), I.CHORD_LABEL[q]))
lines.append('const char *sg_chordtypes = %s;' % cstr(' '.join(ct)))

# filter programs
frows = []
for name, prog in I.FILTERS.items():
    frows.append('%s\t%s\t%s' % (name, hexprog(prog), SCALE8580.get(name, '')))
lines.append('const char *sg_filtertext[] = {')
for c in chunks('\n'.join(frows) + '\n', 3000):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')

# small maps: REMOVED, MAP8580, PUNCH
lines.append('const char *sg_removed = %s;' % cstr('\n'.join('%s\t%s' % kv for kv in I.REMOVED.items()) + '\n'))
lines.append('const char *sg_map8580[] = {')
for c in chunks('\n'.join('%s\t%s' % kv for kv in GL.MAP8580.items()) + '\n'):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')
prow = []
for model, d in PUNCH.items():
    for n, v in d.items():
        prow.append('%d\t%s\t%.2f' % (model, n, v))
lines.append('const char *sg_punchtext[] = {')
for c in chunks('\n'.join(prow) + '\n', 3000):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')

# measured spectra and loudness (timbre.py, dynamics.py)
try:
    from sidgen import loudness_table as LT
    srow = ['%s\t%s' % (n, ','.join('%.2f' % v for v in sp)) for n, sp in LT.SPECTRA.items()]
    trow = ['%s\t%.2f' % (n, v) for n, v in LT.TIMBRE.items()]
    ref = LT.REF_PITCH
    catd = getattr(LT, 'CAT_DEFAULT', {})
except Exception:
    srow, trow, ref, catd = [], [], {}, {}
lines.append('const char *sg_spectratext[] = {')
for c in chunks('\n'.join(srow) + '\n', 3000):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')
lines.append('const char *sg_timbretext[] = {')
for c in chunks('\n'.join(trow) + '\n', 3000):
    lines.append('  %s,' % cstr(c))
lines.append('  0};')
lines.append('const char *sg_refpitch = %s;' % cstr(' '.join('%s=%d' % kv for kv in ref.items())))
lines.append('const char *sg_catdefault = %s;' % cstr(' '.join('%s=%.2f' % kv for kv in catd.items())))

open(OUT, 'w').write('\n'.join(lines) + '\n')
print('%s: %d style variants, %d instruments, %d arp templates, %d filters, %d bytes'
      % (OUT, len(variants), len(rows), len(arows), len(frows), os.path.getsize(OUT)))
